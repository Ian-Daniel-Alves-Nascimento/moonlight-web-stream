export function iconElement(path: string): HTMLSpanElement {
    const span = document.createElement("span")
    span.classList.add("lt-icon")
    span.setAttribute("aria-hidden", "true")
    span.innerHTML = `<svg viewBox="0 0 24 24"><path d="${path}"/></svg>`
    return span
}

/// A button with an icon above (or beside) its label.
export function iconButton(path: string, label: string, ...classes: string[]): HTMLButtonElement {
    const button = document.createElement("button")
    button.type = "button"
    button.classList.add("lt-button", ...classes)
    setIconLabel(button, path, label)

    return button
}

/// Replaces a button's content with an icon and a label.
export function setIconLabel(button: HTMLButtonElement, path: string, label: string) {
    const text = document.createElement("span")
    text.classList.add("lt-button-label")
    text.innerText = label

    button.replaceChildren(iconElement(path), text)
}
